/**
 * Scans the img folder and writes js/sign-images-data.js with the list of
 * image filenames (excluding logo.png). Run this when you add or remove images:
 *
 *   node scripts/build-sign-images.js
 */

const fs = require('fs');
const path = require('path');

const IMG_DIR = path.join(__dirname, '..', 'img');
const OUTPUT_FILE = path.join(__dirname, '..', 'js', 'sign-images-data.js');
const EXCLUDE = ['logo.png'];
const EXTENSIONS = new Set(['.png', '.jpg', '.jpeg', '.gif', '.webp']);

const files = fs.readdirSync(IMG_DIR);
const images = files
  .filter(function (file) {
    const ext = path.extname(file).toLowerCase();
    return EXTENSIONS.has(ext) && !EXCLUDE.includes(file);
  })
  .sort();

const content =
  '// Auto-generated by scripts/build-sign-images.js – do not edit\n' +
  'window.SIGN_IMAGES = ' +
  JSON.stringify(images) +
  ';\n';

fs.writeFileSync(OUTPUT_FILE, content, 'utf8');
console.log('Wrote ' + OUTPUT_FILE + ' with ' + images.length + ' image(s):', images.join(', '));
